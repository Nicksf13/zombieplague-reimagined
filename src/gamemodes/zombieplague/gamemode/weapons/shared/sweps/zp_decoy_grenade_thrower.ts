SWEP.Initialize = function (): void { this.SetHoldType("grenade"); };
SWEP.PrimaryAttack = function (): void {
    if (!IsFirstTimePredicted() || !this.CanPrimaryAttack()) return;
    const owner = this.GetOwner();
    if (!IsValid(owner) || !owner.Alive() || owner.Team() !== TEAM_HUMANS) return;
    if (SERVER && !ZPDecoy.Throw(this)) return;
    this.SetNextPrimaryFire(CurTime() + 1);
    this.SendWeaponAnim(ACT_VM_THROW); owner.SetAnimation(PLAYER_ATTACK1);
    if (!SERVER) return;
    this.EmitSound(file.Exists("sound/weapons/pinpull.wav", "GAME") ? "weapons/pinpull.wav" : "weapons/slam/throw.wav");
    this.TakePrimaryAmmo(1);
    // The callback removes only this consumed weapon, never a new copy bought during the delay.
    timer.Simple(0.6, () => { if (IsValid(this)) this.Remove(); });
};
SWEP.SecondaryAttack = function (): void {};
SWEP.Reload = function (): void {};
SWEP.OnDrop = function (): void { if (SERVER) this.Remove(); };
